"""export_bundle — the always-available adapter (never blocks a demo). Produces a ZIP with the rendered page,
metadata, schema and a sitemap entry, written atomically (temp file + rename)."""

from __future__ import annotations

import io
import json
import os
import zipfile
from pathlib import Path

from app.adapters.base import PublishContext, PublishResult
from app.core.config import get_settings
from app.services.article_doc import to_markdown
from app.services.sitemap import entry

README = """LayerFlow export bundle
=======================

Article : {title}
Category: {category}  ({route})
Slug    : {slug}
URL     : {url}

Upload steps
1. Copy index.html to {route}/{slug}/index.html on the web server (or into the CMS).
2. Add the contents of sitemap-entry.xml inside <urlset> of /sitemap.xml.
3. meta.json and schema.json hold the SEO payload and JSON-LD if your CMS needs them separately.

Generated by {powered_by}. Content hash {hash}.
"""


def bundle_bytes(ctx: PublishContext) -> bytes:
    seo = ctx.payload.get("seo") or {}
    art = ctx.payload.get("article") or {}
    url = seo.get("canonical_url") or f"{ctx.site_url.rstrip('/')}{ctx.route}/{ctx.slug}"
    meta = {
        "title_tag": seo.get("title_tag"),
        "meta_description": seo.get("meta_description"),
        "canonical_url": url,
        "slug": ctx.slug,
        "category": ctx.category,
        "route": ctx.route,
        "h1": seo.get("h1") or art.get("title"),
        "og": seo.get("og"),
        "twitter": seo.get("twitter"),
        "primary_keyword": seo.get("primary_keyword"),
        "secondary_keywords": seo.get("secondary_keywords"),
        "published_at": ctx.published_at.isoformat(),
        "content_hash": ctx.content_hash,
        "sources": art.get("sources_used"),
    }
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("index.html", ctx.html)
        zf.writestr("article.md", to_markdown(art))
        zf.writestr("article.json", json.dumps(art, indent=2, ensure_ascii=False))
        zf.writestr("meta.json", json.dumps(meta, indent=2, ensure_ascii=False))
        zf.writestr("schema.json", json.dumps(seo.get("json_ld") or [], indent=2, ensure_ascii=False))
        zf.writestr("sitemap-entry.xml", entry(url, ctx.published_at))
        zf.writestr(
            "README.txt",
            README.format(
                title=art.get("title"), category=ctx.category, route=ctx.route, slug=ctx.slug, url=url,
                powered_by="LayerFlow", hash=ctx.content_hash[:12],
            ),
        )
    return buf.getvalue()


def write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    tmp.write_bytes(data)
    os.replace(tmp, path)


class ExportBundleAdapter:
    name = "export"

    def _path(self, ctx: PublishContext) -> Path:
        return Path(get_settings().artifacts_dir) / ctx.tenant_slug / ctx.slug / f"{ctx.content_hash[:12]}.zip"

    async def validate(self, ctx: PublishContext) -> list[str]:
        return [] if ctx.slug else ["Slug missing"]

    async def publish(self, ctx: PublishContext, *, dry_run: bool = False) -> PublishResult:
        path = self._path(ctx)
        url = (ctx.payload.get("seo") or {}).get("canonical_url") or f"{ctx.site_url.rstrip('/')}{ctx.route}/{ctx.slug}"
        if dry_run:
            return PublishResult(remote_id=ctx.slug, live_url=url, status="dry_run", artifacts=["index.html", "article.md", "meta.json", "schema.json", "sitemap-entry.xml"])
        write_atomic(path, bundle_bytes(ctx))
        return PublishResult(
            remote_id=ctx.slug,
            live_url=url,
            artifacts=[str(path)],
            artifact_path=str(path),
            warnings=["Export bundle created — upload it to the site (no direct site access configured)"],
        )

    async def update(self, remote_id: str, ctx: PublishContext) -> PublishResult:
        return await self.publish(ctx)

    async def unpublish(self, remote_id: str, ctx: PublishContext) -> None:
        return None

    async def health(self) -> tuple[bool, str]:
        root = Path(get_settings().artifacts_dir)
        try:
            root.mkdir(parents=True, exist_ok=True)
            probe = root / ".probe"
            probe.write_text("ok")
            probe.unlink()
            return True, f"Writable: {root}"
        except OSError as exc:
            return False, f"Artifacts directory not writable: {exc}"
